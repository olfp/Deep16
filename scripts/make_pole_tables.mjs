#!/usr/bin/env node
// scripts/make_pole_tables.mjs - emit the D16 data tables for the Pole renderer.
//
// The tables are the same numbers the JS model uses (js/deep16_pole_model.js);
// tests/pole-asm.test.js checks that the checked-in file still matches, so
// this script is the only thing that should ever rewrite it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

vm.runInThisContext(fs.readFileSync(path.join(ROOT, 'js/deep16_pole_model.js'), 'utf8'),
                    { filename: 'js/deep16_pole_model.js' });
const Model = vm.runInThisContext('Deep16PoleModel');

function words(values, perLine = 16) {
  const lines = [];
  for (let i = 0; i < values.length; i += perLine) {
    const chunk = values.slice(i, i + perLine)
      .map((v) => (v < 0 ? `0x${(v & 0xFFFF).toString(16).toUpperCase()}` : `${v}`));
    lines.push(`    .word ${chunk.join(', ')}`);
  }
  return lines.join('\n');
}

const out = `; pole_tables.asm - data tables for the Pole road renderer.
;
; Generated by scripts/make_pole_tables.mjs from js/deep16_pole_model.js.
; Do not edit by hand: the test checks these words against the JS model.

.equ CURVE_TBL 0x0A00
.equ WIDTH_TBL 0x0A40
.equ HILL_TBL  0x0A80
.equ SPRITE_W  0x0AA0
.equ SPRITE_H  0x0AA4
.equ SPRITE_G  0x0AA8

.org 0x0A00
curve_tbl:
${words(Model.CURVE_TRACK)}

.org 0x0A40
width_tbl:
${words(Model.WIDTH_TRACK)}

.org 0x0A80
hill_tbl:
${words(Model.HILL_OFFSETS)}

.org 0x0AA0
sprite_w:
${words(Model.SPRITE_W)}

.org 0x0AA4
sprite_h:
${words(Model.SPRITE_H)}

.org 0x0AA8
sprite_groups:
${words(Model.SPRITE_GROUPS)}
`;

const file = path.join(ROOT, 'asm/pole/pole_tables.asm');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log(`wrote ${path.relative(ROOT, file)}`);
