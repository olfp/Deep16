#!/usr/bin/env node
// scripts/make_flash_assets.mjs - build the FiT graphics flash blob.
//
// The simulation must not carry a graphics ROM. The tile bank, sprite bank and
// palettes are flash contents, loaded at run time the same way the board will
// load them. This script packages the existing art generators into one blob:
//
//   magic "D16G" | version u16 | tileWords u16 | spriteWords u16 |
//   paletteWords u16 | little-endian 16-bit words
//
// Usage:
//   node scripts/make_flash_assets.mjs            # write js/deep16_flash_assets.js
//   node scripts/make_flash_assets.mjs --check    # exit 1 if stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  PALETTE_RGB332,
  TILE_BANK_WORDS,
  readFontWords,
  tileFontWords,
} from './make_tile_font.mjs';
import { SPRITE_WORDS as GENERATED_SPRITE_WORDS, birdSpriteWords } from './make_bird_sprite.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const MAGIC = 'D16G';
export const VERSION = 1;
export const ASSET_BASE = 0x300000;
export const TILE_WORDS = TILE_BANK_WORDS;      // 128 tiles x 32 words
export const SPRITE_WORDS = 6144;               // 24 groups x 256
export const PALETTE_WORDS = 48;                // text, art, sprite banks
export const HEADER_BYTES = 12;
export const TARGET = path.join(ROOT, 'js', 'deep16_flash_assets.js');

export function buildAssetWords() {
  const font = readFontWords(path.join(ROOT, 'rtl', 'dvi', 'ttyp0-8x15.hex'));
  const italic = readFontWords(path.join(ROOT, 'rtl', 'dvi', 'ttyp0-8x15-italic.hex'));
  const tiles = tileFontWords(font, italic);
  const sprites = birdSpriteWords();
  const palette = [...PALETTE_RGB332, ...PALETTE_RGB332, ...PALETTE_RGB332];
  if (tiles.length !== TILE_WORDS) throw new Error(`tile words ${tiles.length} != ${TILE_WORDS}`);
  if (sprites.length !== GENERATED_SPRITE_WORDS) {
    throw new Error(`sprite words ${sprites.length} != ${GENERATED_SPRITE_WORDS}`);
  }
  if (palette.length !== PALETTE_WORDS) throw new Error(`palette words ${palette.length} != ${PALETTE_WORDS}`);
  return { tiles, sprites, palette };
}

export function buildAssetBlob(words = buildAssetWords()) {
  const total = HEADER_BYTES + 2 * (TILE_WORDS + SPRITE_WORDS + PALETTE_WORDS);
  const buf = Buffer.alloc(total, 0);
  buf.write(MAGIC, 0, 4, 'ascii');
  buf.writeUInt16LE(VERSION, 4);
  buf.writeUInt16LE(TILE_WORDS, 6);
  buf.writeUInt16LE(SPRITE_WORDS, 8);
  buf.writeUInt16LE(PALETTE_WORDS, 10);
  let at = HEADER_BYTES;
  for (const list of [words.tiles, words.sprites, words.palette]) {
    for (const w of list) {
      buf.writeUInt16LE(w & 0xFFFF, at);
      at += 2;
    }
  }
  return buf;
}

export function buildAssetScript(blob = buildAssetBlob()) {
  const b64 = blob.toString('base64');
  return `// Generated by scripts/make_flash_assets.mjs - do not edit.
// Flash contents for the FiT graphics loader: tile bank, sprite bank and the
// three palette banks. This is storage, not engine ROM; the engine powers on
// blank and the loader writes the CPU windows.
const Deep16FlashAssets = {
  base: 0x${ASSET_BASE.toString(16)},
  magic: '${MAGIC}',
  version: ${VERSION},
  tileWords: ${TILE_WORDS},
  spriteWords: ${SPRITE_WORDS},
  paletteWords: ${PALETTE_WORDS},
  bytes: '${b64}',
};
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  const next = buildAssetScript();
  const old = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : null;
  if (next !== old) {
    if (check) {
      console.error('js/deep16_flash_assets.js is out of date with the art generators');
      process.exit(1);
    }
    fs.writeFileSync(TARGET, next);
    console.log(`wrote ${path.relative(ROOT, TARGET)} (${Buffer.byteLength(next)} bytes)`);
  } else {
    console.log('flash assets are current');
  }
}
