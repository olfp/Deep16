// ps2_rx.sv - PS/2 keyboard receiver and Set-2 to ASCII decoder.
//
// Receive-only: the FPGA never drives the PS/2 clock or data lines. The
// keyboard's open-collector lines are pulled up to 5 V, so they must be level
// shifted to 3.3 V before they reach the FPGA; the GW1NR-9 absolute maximum
// I/O voltage is 3.75 V (DS117).
//
// Frame: start (0), eight data bits LSB first, odd parity, stop (1), sampled
// on the falling edge of the synchronised PS/2 clock. A frame that fails the
// start/stop/parity check is dropped and sets frame_error.
//
// The Set-2 decoder tracks break (0xF0), extended (0xE0), Shift/Ctrl/Alt/Caps
// and emits one character for each make code that has a mapping. The mapping
// is a 2048 x 8 BSRAM pROM addressed by {ctrl, caps, shift, scan_code}; it is
// generated by scripts/make_ps2map.mjs (ps2map.hex) and carries the German
// QWERTZ layout, including the Latin-1 umlauts.
//
// Extended keys and AltGr are remapped to synthetic pROM entries (0x90.. and
// 0x80..): the arrows/Home/End emit the Emacs control bytes, and AltGr gives
// the German punctuation that is not on a keycap. Their make codes collide
// with the numeric keypad, so the remap is the only way to keep one table.
module ps2_rx #(
  parameter int CLK_HZ = 6_750_000
) (
  input  logic       clk,
  input  logic       rst,
  input  logic       ps2_clk,
  input  logic       ps2_data,
  output logic       valid,        // one-cycle pulse for a new ASCII byte
  output logic [7:0] ascii,
  output logic [7:0] scan_code,    // last received code, for debug
  output logic [3:0] modifiers,    // {caps, alt, ctrl, shift}
  output logic       frame_error,  // sticky until the next good frame
  // One-cycle pulse for every frame with good start/parity/stop, including
  // the ACK (0xFA) and BAT (0xAA) codes the host init waits for.
  output logic       frame_valid,
  // Synchronised pin levels for the host-side GPIO timing.
  output logic       dbg_clk, dbg_data
);

  // 2 ms at the CPU clock. A Set-2 frame at 16.7 kHz is about 0.66 ms, so a
  // clock that stops mid-frame resynchronises well before the next key.
  localparam logic [15:0] TIMEOUT = 16'(CLK_HZ / 500);

  // ---- input synchronisers ----------------------------------------------
  logic clk_meta, clk_sync;
  logic data_meta, data_sync;

  always_ff @(posedge clk) begin
    if (rst) begin
      clk_meta   <= 1'b1;
      clk_sync   <= 1'b1;
      data_meta  <= 1'b1;
      data_sync  <= 1'b1;
    end else begin
      clk_meta   <= ps2_clk;
      clk_sync   <= clk_meta;
      data_meta  <= ps2_data;
      data_sync  <= data_meta;
    end
  end

  // The cable and the external 5V level shifter can ring, and one extra
  // falling edge in the middle of a frame shifts every remaining bit. Accept
  // an edge only after the clock has been low for four consecutive samples:
  // a PS/2 bit lasts hundreds of 6.75 MHz clocks, so the added latency is
  // harmless, while a short glitch is rejected.
  logic [3:0] clk_low_run;
  logic       clk_seen_high;
  always_ff @(posedge clk) begin
    if (rst) begin
      clk_low_run   <= 4'd0;
      clk_seen_high <= 1'b0;
    end else if (clk_sync) begin
      clk_low_run   <= 4'd0;
      clk_seen_high <= 1'b1;
    end else if (clk_low_run != 4'd15) begin
      clk_low_run <= clk_low_run + 4'd1;
    end
  end
  wire clk_fall = clk_seen_high && !clk_sync && (clk_low_run == 4'd3);

  assign frame_valid = code_valid;
  assign dbg_clk  = clk_sync;
  assign dbg_data = data_sync;

  // ---- frame receiver ---------------------------------------------------
  // frame is shifted with the new bit at the MSB. After the 11th sample
  // (stop), frame[0] = start, frame[8:1] = data (LSB first), frame[9] =
  // parity and frame[10] = stop.
  logic [10:0] frame;
  logic [3:0]  bit_cnt;
  logic        frame_busy, frame_done;
  logic [15:0] timeout;
  logic        code_valid;
  logic [7:0]  code;

  always_ff @(posedge clk) begin
    if (rst) begin
      frame       <= 11'd0;
      bit_cnt     <= 4'd0;
      frame_busy  <= 1'b0;
      frame_done  <= 1'b0;
      timeout     <= 16'd0;
      code_valid  <= 1'b0;
      code        <= 8'd0;
      frame_error <= 1'b0;
    end else begin
      code_valid <= 1'b0;

      if (clk_fall) begin
        timeout <= 16'd0;
        if (!frame_busy) begin
          // A start bit is low; any other falling edge is noise.
          if (!data_sync) begin
            frame      <= 11'd0;
            frame_busy <= 1'b1;
            bit_cnt    <= 4'd1;
          end
        end else begin
          frame <= {data_sync, frame[10:1]};
          if (bit_cnt == 4'd10) begin
            frame_busy <= 1'b0;
            bit_cnt    <= 4'd0;
            frame_done <= 1'b1;
          end else begin
            bit_cnt <= bit_cnt + 4'd1;
          end
        end
      end else if (frame_busy) begin
        if (timeout >= TIMEOUT) begin
          frame_busy  <= 1'b0;
          bit_cnt     <= 4'd0;
          frame_done  <= 1'b0;
          timeout     <= 16'd0;
          frame_error <= 1'b1;
        end else begin
          timeout <= timeout + 16'd1;
        end
      end

      // The frame register was updated on the stop edge; check it here, one
      // cycle later, so the check sees the stop bit.
      if (frame_done) begin
        frame_done <= 1'b0;
        if (frame[0] == 1'b0 && frame[10] == 1'b1 &&
            ((^frame[8:1]) ^ frame[9]) == 1'b1) begin
          code        <= frame[8:1];
          code_valid  <= 1'b1;
          frame_error <= 1'b0;
        end else begin
          frame_error <= 1'b1;
        end
      end
    end
  end

  // ---- Set-2 decoder ----------------------------------------------------
  logic [7:0] code_q;
  logic       break_flag, ext_flag;
  logic       shift, ctrl, alt, caps;
  logic       decode_req;

  assign modifiers = {caps, alt, ctrl, shift};

  // Extended keys and AltGr use synthetic pROM entries (0x80.. for AltGr,
  // 0x90.. for the arrows), so the map address stays the plain
  // {ctrl, caps, shift, code} and no mux sits on the BSRAM address pins. The
  // device is at 4,320/4,320 CLS; this is the cheapest form that fits.
  logic [7:0] remap_code;
  always_comb begin
    remap_code = 8'h00;
    if (ext_flag) begin
      case (code)
        8'h6B: remap_code = 8'h90;   // Left  -> C-B
        8'h74: remap_code = 8'h91;   // Right -> C-F
        8'h75: remap_code = 8'h92;   // Up    -> C-P
        8'h72: remap_code = 8'h93;   // Down  -> C-N
        8'h6C: remap_code = 8'h94;   // Home  -> C-A
        8'h69: remap_code = 8'h95;   // End   -> C-E
        default: ;
      endcase
    end else if (alt) begin
      case (code)
        8'h15: remap_code = 8'h80;   // Q -> @
        8'h3d: remap_code = 8'h81;   // 7 -> {
        8'h3e: remap_code = 8'h82;   // 8 -> [
        8'h46: remap_code = 8'h83;   // 9 -> ]
        8'h45: remap_code = 8'h84;   // 0 -> }
        8'h4e: remap_code = 8'h85;   // ß -> backslash
        8'h41: remap_code = 8'h86;   // , -> |
        8'h5b: remap_code = 8'h87;   // + -> ~
        8'h1e: remap_code = 8'h88;   // 2 -> ²
        8'h26: remap_code = 8'h89;   // 3 -> ³
        8'h3a: remap_code = 8'h8a;   // M -> µ
        8'h24: remap_code = 8'h8b;   // E -> €
        default: ;
      endcase
    end
  end

  always_ff @(posedge clk) begin
    if (rst) begin
      code_q     <= 8'd0;
      break_flag <= 1'b0;
      ext_flag   <= 1'b0;
      shift      <= 1'b0;
      ctrl       <= 1'b0;
      alt        <= 1'b0;
      caps       <= 1'b0;
      decode_req <= 1'b0;
      scan_code  <= 8'd0;
    end else begin
      decode_req <= 1'b0;

      if (code_valid) begin
        code_q    <= code;
        scan_code <= code;

        if (code == 8'hAA || code == 8'hFA || code == 8'hEE || code >= 8'hFC) begin
          // BAT complete, ACK, echo, resend/error: no key.
          break_flag <= 1'b0;
          ext_flag   <= 1'b0;
        end else if (code == 8'hF0) begin
          break_flag <= 1'b1;
        end else if (code == 8'hE0) begin
          ext_flag <= 1'b1;
        end else begin
          if (code == 8'h12 || code == 8'h59) begin
            shift <= !break_flag;
          end else if (code == 8'h14) begin
            ctrl <= !break_flag;
          end else if (code == 8'h11) begin
            // Both Alts set the same state: right Alt is the German AltGr, and
            // the left Alt is not used for typing on this console.
            alt <= !break_flag;
          end else if (code == 8'h58) begin
            if (!break_flag) caps <= ~caps;
          end else if (!break_flag) begin
            // Extended and AltGr keys are looked up at their synthetic code;
            // a key with no synthetic entry emits nothing rather than the
            // keypad digit it shares a make code with.
            if (remap_code != 8'h00) code_q <= remap_code;
            if ((!ext_flag && !alt) || remap_code != 8'h00) decode_req <= 1'b1;
          end
          break_flag <= 1'b0;
          ext_flag   <= 1'b0;
        end
      end
    end
  end

  // ---- scan-code to ASCII map -------------------------------------------
  // The address is stable between scan codes, so a two-cycle pipeline is
  // enough for the BSRAM pROM's registered output.
  logic [7:0] ps2map [0:2047];
  initial $readmemh("ps2map.hex", ps2map);

  logic [7:0] map_q;
  logic [1:0] map_wait;

  always_ff @(posedge clk) begin
    if (rst) begin
      map_q    <= 8'd0;
      map_wait <= 2'd0;
      valid    <= 1'b0;
      ascii    <= 8'd0;
    end else begin
      map_q <= ps2map[{ctrl, caps, shift, code_q}];
      valid <= 1'b0;

      if (decode_req) begin
        map_wait <= 2'd2;
      end else if (map_wait != 2'd0) begin
        if (map_wait == 2'd1) begin
          if (map_q != 8'd0) begin
            ascii <= map_q;
            valid <= 1'b1;
          end
          map_wait <= 2'd0;
        end else begin
          map_wait <= map_wait - 2'd1;
        end
      end
    end
  end

endmodule
